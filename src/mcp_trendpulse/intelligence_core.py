def _safe_origin(plan: Plan) -> None:
    parsed = urlsplit(plan.url)
    if parsed.username or parsed.password or parsed.fragment:
        raise IntelligenceError("Credential-bearing or fragment URL refused")
    local_ports = {"rsshub_local": 1200, "changedetection_local": 5000}
    if plan.allow_loopback and plan.source in local_ports:
        if (parsed.scheme == "http" and parsed.hostname == "127.0.0.1"
                and parsed.port == local_ports[plan.source] and
                parsed.username is None and parsed.password is None):
            return
    if plan.allow_loopback:
        raise IntelligenceError("Unapproved self-hosted loopback address")
    if parsed.scheme != "https" or parsed.hostname not in _HOSTS or parsed.port not in (None, 443):
        raise IntelligenceError("Source plan contains an unapproved outbound host")


class _NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        return None


class BudgetCache:
    """Per-source UTC-day request budget with durable cache and SQLite locking."""

    def __init__(self, root: Path | None = None):
        if root is None:
            raw = os.environ.get("TRENDPULSE_INTEL_CACHE_DIR", "")
            root = Path(raw) if raw else Path.home() / ".mcp-trendpulse" / "intelligence"
        root = root.expanduser()
        if not root.is_absolute() or root.is_symlink():
            raise IntelligenceError("Cache root must be an absolute non-symlink directory")
        root.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.db = root / "intelligence.sqlite3"
        if self.db.is_symlink():
            raise IntelligenceError("Cache database may not be a symlink")
        with self._connect() as conn:
            conn.execute("CREATE TABLE IF NOT EXISTS cache (id TEXT PRIMARY KEY, until REAL NOT NULL, body TEXT NOT NULL)")
            conn.execute("CREATE TABLE IF NOT EXISTS budget (source TEXT NOT NULL, day TEXT NOT NULL, used INTEGER NOT NULL, PRIMARY KEY(source, day))")
            conn.execute("CREATE TABLE IF NOT EXISTS cooldown (source TEXT PRIMARY KEY, until REAL NOT NULL)")

    def _connect(self):
        return sqlite3.connect(str(self.db), timeout=5, isolation_level=None)

    def cached(self, key: str) -> dict[str, Any] | None:
        with self._connect() as conn:
            row = conn.execute("SELECT body FROM cache WHERE id=? AND until>?", (key, time.time())).fetchone()
        return json.loads(row[0]) if row else None

    def blocked(self, source: str) -> bool:
        with self._connect() as conn:
            row = conn.execute("SELECT until FROM cooldown WHERE source=?", (source,)).fetchone()
        return bool(row and row[0] > time.time())

    def cool_down(self, source: str, seconds: int = 90) -> None:
        """Treat provider 429/503 as a short shared circuit breaker."""
        until = time.time() + max(30, min(seconds, 300))
        with self._connect() as conn:
            conn.execute(
                "INSERT INTO cooldown(source, until) VALUES (?, ?) "
                "ON CONFLICT(source) DO UPDATE SET until=MAX(until, excluded.until)",
                (source, until),
            )

    def reserve(self, source: str, cap: int) -> None:
        day = datetime.now(timezone.utc).date().isoformat()
        with self._connect() as conn:
            conn.execute("BEGIN IMMEDIATE")
            row = conn.execute("SELECT used FROM budget WHERE source=? AND day=?", (source, day)).fetchone()
            if row and row[0] >= cap:
                conn.rollback()
                raise IntelligenceError(f"{source} free-only daily request cap reached")
            conn.execute("INSERT INTO budget(source, day, used) VALUES (?, ?, 1) ON CONFLICT(source, day) DO UPDATE SET used=used+1", (source, day))
            conn.commit()

    def save(self, key: str, output: dict[str, Any], ttl: int) -> None:
        with self._connect() as conn:
            conn.execute("INSERT OR REPLACE INTO cache(id, until, body) VALUES (?, ?, ?)",
                         (key, time.time() + ttl, json.dumps(output, ensure_ascii=False)))


def collect(plan: Plan, *, cache: BudgetCache | None = None,
            fetch: bool = False, timeout: int = DEFAULT_TIMEOUT,
            env: dict[str, str] | None = None) -> dict[str, Any]:
    """Explicit fetching only. Never retry, follow redirects, or exceed a source cap."""
    _safe_origin(plan)
    if not fetch:
        return {"status": "planned", **plan.public()}
    if not isinstance(timeout, int) or not 2 <= timeout <= 30:
        raise IntelligenceError("timeout must be between 2 and 30 seconds")
    store = cache if cache is not None else BudgetCache()
    identity = hashlib.sha256(json.dumps(
        [plan.source, plan.method, plan.url, plan.body, plan.headers],
        sort_keys=True).encode()).hexdigest()
    # Fast path: repeated requests avoid filesystem lock overhead entirely.
    previously = store.cached(identity)
    if previously is not None:
        return {**previously, "cache_hit": True}

    # Independent query hashes are never serialized with one another.
    # Across threads/processes, only the first identical request uses free quota.
    lock_root = store.db.parent / ".request_locks"
    if lock_root.is_symlink():
        raise IntelligenceError("Request lock directory may not be a symlink")
    lock_root.mkdir(mode=0o700, exist_ok=True)
    lock_path = lock_root / f"{identity}.lock"
    if lock_path.is_symlink():
        raise IntelligenceError("Request lock file may not be a symlink")
    try:
        with FileLock(str(lock_path), timeout=timeout + 5):
            return _collect_under_lock(plan, store, identity, timeout, env)
    except FileLockTimeout as exc:
        raise IntelligenceError("Another identical free-source request is still running") from exc


def _collect_under_lock(
    plan: Plan, store: BudgetCache, identity: str, timeout: int,
    env: dict[str, str] | None,
) -> dict[str, Any]:
    """Recheck cache inside the per-query lock before reserving free API quota."""
    previously = store.cached(identity)
    if previously is not None:
        return {**previously, "cache_hit": True}
    if store.blocked(plan.source):
        return {"source": plan.source, "status": "unavailable",
                "reason": "provider_cooldown", "retry_automatically": False,
                "cache_hit": False}
    store.reserve(plan.source, plan.budget_per_day)
    accepted = {
        "json": "application/json",
        "csv": "text/csv",
        "xml": "application/xml, application/rss+xml, application/atom+xml",
        "text": "text/plain",
    }
    headers = {
        "User-Agent": "mcp-trendpulse-intelligence/0.1 (research; read-only)",
        "Accept": accepted.get(plan.content_type, "application/json"),
        **plan.headers,
    }
    if plan.body is None:
        body = None
    elif plan.body_encoding == "form":
        body = urlencode(plan.body).encode("utf-8")
        headers["Content-Type"] = "application/x-www-form-urlencoded"
    else:
        body = json.dumps(plan.body, separators=(",", ":")).encode("utf-8")
        headers["Content-Type"] = "application/json"
    opener = build_opener(ProxyHandler({}), _NoRedirect())
    try:
        if plan.source == "epo":
            from mcp_trendpulse.intelligence_extended import epo_oauth_token
            from mcp_trendpulse.intelligence_settings import resolved_environment

            headers["Authorization"] = "Bearer " + epo_oauth_token(
                resolved_environment(env, provider="epo"), opener, timeout
            )
        req = Request(plan.url, data=body, headers=headers, method=plan.method)
        with opener.open(req, timeout=timeout) as res:
            kind = res.headers.get("Content-Type", "").lower()
            raw = res.read(MAX_RESPONSE_BYTES + 1)
            if len(raw) > MAX_RESPONSE_BYTES:
                raise IntelligenceError("Response exceeded 256 KiB; narrow your source query")
            if plan.content_type == "json":
                if "json" not in kind:
                    raise IntelligenceError("Source did not return JSON; status cannot be treated as evidence")
                payload = json.loads(raw)
            elif plan.content_type == "csv":
                if "csv" not in kind and "text/plain" not in kind:
                    raise IntelligenceError("Expected CSV response")
                payload = _parse_csv(raw)
            elif plan.content_type == "xml":
                if not any(marker in kind for marker in ("xml", "rss", "atom")):
                    raise IntelligenceError("Expected XML response")
                payload = _parse_xml(raw)
            elif plan.content_type == "text":
                payload = {"lines": raw.decode("utf-8", "strict").splitlines()[:20]}
            else:
                raise IntelligenceError("Unknown content type")
    except HTTPError as exc:
        failure = {"source": plan.source, "status": "unavailable", "reason": "HTTPError",
                   "http_status": exc.code, "retry_automatically": False, "cache_hit": False}
        if exc.code in (429, 503):
            retry_header = exc.headers.get("Retry-After", "") if exc.headers else ""
            delay = int(retry_header) if retry_header.isdigit() and len(retry_header) <= 6 else 90
            store.cool_down(plan.source, delay)
        store.save(identity, failure, 60)
        return failure
    except (URLError, TimeoutError, OSError, UnicodeError, json.JSONDecodeError,
            ElementTree.ParseError, csv.Error) as exc:
        failure = {"source": plan.source, "status": "unavailable",
                   "reason": type(exc).__name__, "retry_automatically": False,
                   "cache_hit": False}
        store.save(identity, failure, 45)
        return failure
    from mcp_trendpulse.intelligence_evidence import (
        UnexpectedSourceShape, evidence_projection,
    )
    try:
        observations = evidence_projection(plan.source, payload)
    except UnexpectedSourceShape as exc:
        failure = {
            "source": plan.source, "status": "invalid_source_shape",
            "reason": str(exc), "retry_automatically": False, "cache_hit": False,
        }
        store.save(identity, failure, 120)
        return failure
    reduced = _bound_payload(payload)
    output = {
        "observations": _bound_payload(observations),
        "source": plan.source,
        "wave": plan.wave,
        "source_url": plan.url,
        "source_documentation": plan.docs,
        "status": "observed",
        "retrieved_at": datetime.now(timezone.utc).isoformat(),
        "evidence_level": "public_source_snapshot_not_purchasing_validation",
        "caution": plan.caution,
        "data": reduced,
        "cache_hit": False,
    }
    store.save(identity, output, 3600)
    return output


def _bound_payload(value: Any) -> Any:
    """Return valid bounded JSON rather than inventing records from incomplete data."""
    if isinstance(value, list):
        return [_bound_payload(x) for x in value[:20]]
    if isinstance(value, dict):
        return {str(k): _bound_payload(v) for k, v in list(value.items())[:50]}
    if isinstance(value, str):
        return value[:3000]
    return value if value is None or isinstance(value, (int, float, bool)) else str(value)[:300]



def _parse_csv(raw: bytes) -> dict[str, Any]:
    """Bounded CSV evidence: preserve header labels and first 20 observations."""
    rows = csv.DictReader(io.StringIO(raw.decode("utf-8-sig", "strict")))
    fields = (rows.fieldnames or [])[:40]
    if not fields:
        raise IntelligenceError("CSV has no column headers")
    values = []
    for index, row in enumerate(rows):
        if index >= 20:
            break
        values.append({key: (row.get(key) or "")[:1000] for key in fields})
    return {"columns": fields, "rows": values, "note": "First 20 rows of bounded public CSV response"}


def _parse_xml(raw: bytes) -> dict[str, Any]:
    """Bounded, non-resolving stdlib XML parser; no DTD or external entities."""
    if b"<!DOCTYPE" in raw.upper() or b"<!ENTITY" in raw.upper():
        raise IntelligenceError("DTD and entity declarations are prohibited")
    root = ElementTree.fromstring(raw)
    result = []
    for node in root.iter():
        if len(result) >= 100:
            break
        text = (node.text or "").strip()
        if not text:
            continue
        result.append({
            "element": node.tag.rsplit("}", 1)[-1][:90],
            "text": text[:500],
        })
    return {
        "root": root.tag.rsplit("}", 1)[-1][:90],
        "observations": result,
        "note": "Selected element text; nested XML attributes and relationships not inferred",
    }
