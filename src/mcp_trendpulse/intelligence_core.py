"""Opt-in, free-only, read-only market intelligence evidence collector.

Does not enable network activity at import time, add scheduled tasks, or call
billable provider APIs. Public endpoints are fixed by source-specific builders.
Responses remain third-party evidence, not instructions or buying signals.
"""

