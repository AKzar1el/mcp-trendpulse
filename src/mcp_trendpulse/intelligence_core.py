MAX_RESPONSE_BYTES = 256 * 1024
MAX_RESULT_CHARS = 24000
DEFAULT_TIMEOUT = 12
MAX_LIMIT = 20


class IntelligenceError(ValueError):
    """Invalid input, exhausted budget, or explicitly unavailable source."""


@dataclass(frozen=True)
class Plan:
    source: str
    wave: int
    method: str
    url: str
    docs: str
    caution: str
    budget_per_day: int
    body: dict[str, Any] | None = None
    headers: dict[str, str] = field(default_factory=dict)
    content_type: str = "json"
    body_encoding: str = "json"
    # Network origin is generated by a trusted builder; never user-provided.
    allow_loopback: bool = False

    def public(self) -> dict[str, Any]:
        parsed = urlsplit(self.url)
        # No API secrets in URLs: optional provider keys belong in headers.
        return {
            "source": self.source,
            "wave": self.wave,
            "method": self.method,
            "url": self.url,
            "body": self.body,
            "headers": {k: "<configured>" for k in self.headers},
            "docs": self.docs,
            "caution": self.caution,
            "budget_per_day": self.budget_per_day,
            "host": parsed.hostname,
            "network_performed": False,
        }


def _modules():
    from mcp_trendpulse import intelligence_extended as verified
    from mcp_trendpulse import intelligence_foundation as first
    from mcp_trendpulse import intelligence_commercial as second
    from mcp_trendpulse import intelligence_specialized as third

    return verified, first, second, third


def source_catalog() -> list[dict[str, Any]]:
    """Metadata only: free access does not imply permission to redistribute."""
    sources = {}
    for module in _modules():
        for name, meta in module.SOURCES.items():
            if name not in sources:
                sources[name] = {"id": name, **meta, "fetch_enabled": True}
    return sorted(sources.values(), key=lambda x: (x["wave"], x["id"]))


def plan_source(source: str, *, keyword: str = "", company: str = "",
                dataset: str = "", country: str = "", identifier: str = "",
                limit: int = 10, env: dict[str, str] | None = None,
                lookback_days: int | None = None) -> Plan:
    """Build one bounded request from trusted templates, never an arbitrary URL."""
    if not isinstance(source, str):
        raise IntelligenceError("Source ID must be a string")
    if not isinstance(limit, int) or isinstance(limit, bool) or not 1 <= limit <= MAX_LIMIT:
        raise IntelligenceError("limit must be an integer between 1 and 20")
    if lookback_days is not None and (
        isinstance(lookback_days, bool) or not isinstance(lookback_days, int)
        or not 7 <= lookback_days <= 90
    ):
        raise IntelligenceError("lookback_days must be 7..90 or omitted")
    params = {
        "lookback_days": lookback_days,
        "keyword": _short(keyword, "keyword", 160, optional=True),
        "company": _slug(company, "company", optional=True),
        "dataset": _slug(dataset, "dataset", optional=True),
        "country": _country(country, optional=True),
        "identifier": _short(identifier, "identifier", 128, optional=True),
        "limit": limit,
    }
    from mcp_trendpulse.intelligence_settings import resolved_environment

    environment = resolved_environment(env, provider=source)
    for module in _modules():
        if source in module.SOURCES:
            plan = module.build(source, params, environment)
            _safe_origin(plan)
            return plan
    raise IntelligenceError("Unknown source ID; use source_catalog")


def _short(value: str, name: str, maximum: int, *, optional: bool = False) -> str:
    if not isinstance(value, str):
        raise IntelligenceError(f"{name} must be a string")
    value = value.strip()
    if not value and optional:
        return ""
    if not 1 <= len(value) <= maximum or any(ord(ch) < 32 for ch in value):
        raise IntelligenceError(f"{name} must contain 1-{maximum} printable characters")
    return value


def _slug(value: str, name: str, *, optional: bool = False) -> str:
    value = _short(value, name, 96, optional=optional)
    if value and re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9_.-]{0,95}", value) is None:
        raise IntelligenceError(f"{name} must be an ASCII identifier/board slug")
    return value


def _country(value: str, *, optional: bool = False) -> str:
    value = _short(value, "country", 2, optional=optional).upper()
    if value and re.fullmatch(r"[A-Z]{2}", value) is None:
        raise IntelligenceError("country must be an ISO two-letter country code")
    return value


def _required(value: str, name: str) -> str:
    if not value:
        raise IntelligenceError(f"{name} is required for this source")
    return value


